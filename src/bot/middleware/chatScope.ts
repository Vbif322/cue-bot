import type { NextFunction } from 'grammy';

import type { BotContext } from '../types.js';

/**
 * Единственные команды, на которые бот отвечает внутри группового чата.
 * Всё остальное групповое в бота не попадает — см. ниже почему.
 */
export const GROUP_COMMANDS = [
  'start_announcements',
  'stop_announcements',
] as const;

const GROUP_CHAT_TYPES = new Set(['group', 'supergroup']);

/**
 * ТОЧКА ОТСЕЧЕНИЯ ГРУППОВЫХ АПДЕЙТОВ.
 *
 * Весь остальной бот написан в расчёте на личку и ключует состояние ТОЛЬКО по
 * `ctx.from.id`, без оглядки на чат. Поэтому, как только бот попадает в группу,
 * без этого фильтра ломается сразу шесть мест:
 *
 *  - `menuHandlers` ловит `.hears()` на «Турниры»/«Мои матчи»/«Профиль» —
 *    вообще без диалогового состояния: любой участник выгружает список в чат;
 *  - `inviteCommands` читает произвольный текст как `@username` и шлёт
 *    приглашение;
 *  - `matchCommands` читает текст как счёт по фреймам (это МОЖЕТ продвинуть
 *    сетку) либо как время матча;
 *  - визард создания турнира принимает групповое сообщение как свой ввод;
 *  - `profileCommand` перезаписывает имя пользователя;
 *  - `wizardGuard` отвечает «Завершите wizard» прямо в группу.
 *
 * `dialog_sessions` живут часами, так что достаточно одного администратора с
 * незакрытым диалогом в личке. Чинить это правкой шести файлов — значит
 * оставить седьмую дыру при следующем хендлере, поэтому фильтр один и здесь.
 *
 * Порядок в цепочке: ПОСЛЕ `rateLimitMiddleware`, ДО `authMiddleware`.
 *  - до auth — потому что `authMiddleware` делает upsert `users` (транзакция
 *    Postgres) на каждого отправителя; в чате на тысячи человек это заметно;
 *  - после rateLimit — чтобы разрешённые групповые команды остались под
 *    флуд-защитой.
 *
 * Дроп молчаливый: отвечать на каждое сообщение в группе — усилитель
 * злоупотреблений. Именно поэтому не подходит `privateOnly()` из guards.ts,
 * который отвечает текстом.
 *
 * `callback_query` в группе тоже отбрасывается, и это не потеря: единственная
 * клавиатура, которую мы шлём в группу, — URL-кнопка, она callback'ов не
 * порождает. Зато `reg:join` из группы зарегистрировал бы человека, которому
 * бот потом не сможет написать в личку.
 */
export async function chatScopeMiddleware(
  ctx: BotContext,
  next: NextFunction,
): Promise<void> {
  const type = ctx.chat?.type;

  // Апдейты без чата (inline_query, poll_answer, …) — не наша забота.
  if (type === undefined) return next();
  if (type === 'private') return next();

  // Каналы бот не обслуживает вовсе.
  if (!GROUP_CHAT_TYPES.has(type)) return;

  // Бота добавили/выгнали/сменили права — единственный апдейт, ради которого
  // мы вообще слушаем группы.
  if (ctx.myChatMember !== undefined) return next();

  if (GROUP_COMMANDS.some((command) => ctx.hasCommand(command))) return next();

  return;
}
